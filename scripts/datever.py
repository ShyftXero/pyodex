#!/usr/bin/env python3
"""haru-pack style datever: version == UTC build timestamp (YYYYMMDDHHMMSS).

    uv run scripts/datever.py            # print current datever
    uv run scripts/datever.py --write    # stamp src/pyodex/_version.py + CHANGELOG

Monotonic by construction (time only moves forward), PEP 440 valid as a bare
number, and readable as a build date. Env override: PYODEX_VERSION.
"""
from __future__ import annotations

import argparse
import datetime as dt
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERSION_FILE = ROOT / "src" / "pyodex" / "_version.py"
sys.path.insert(0, str(ROOT / "src"))

from pyodex.version import chrome_version, datever  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--at", help="override timestamp, e.g. 20261118140200")
    a = ap.parse_args()
    v = datever(dt.datetime.strptime(a.at, "%Y%m%d%H%M%S").replace(tzinfo=dt.UTC) if a.at else None)
    if not a.write:
        print(v)
        return 0
    VERSION_FILE.write_text(
        "# Generated by scripts/datever.py — do not edit by hand.\n"
        "# Scheme: UTC build timestamp, YYYYMMDDHHMMSS (as used by haru-pack).\n"
        f'__version__ = "{v}"\n'
    )
    log = ROOT / "CHANGELOG.md"
    head = f"## {v}\n\n"
    prev = log.read_text() if log.exists() else "# Changelog\n\n"
    if not prev.endswith("\n\n"):
        prev = prev.rstrip("\n") + "\n\n"
    log.write_text(prev + head + "- build\n\n")
    print(f"{v}  (chrome extension version {chrome_version(v)})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
